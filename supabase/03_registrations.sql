-- 1. Tabel registrations
create table if not exists public.registrations (
    id bigint generated by default as identity primary key,
    event_id bigint not null,
    user_id uuid not null default auth.uid(),
    full_name text not null,
    nim text not null default '',
    email text not null,
    phone text not null,
    status text not null default 'CONFIRMED',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint registrations_event_fk
        foreign key (event_id) references public.events(id) on delete cascade,
    constraint registrations_user_fk
        foreign key (user_id) references public.profiles(id) on delete cascade,
    constraint registrations_event_user_unique unique (event_id, user_id),
    constraint registrations_status_check
        check (status in ('PENDING', 'CONFIRMED', 'CANCELLED')),
    constraint registrations_full_name_check
        check (length(btrim(full_name)) between 3 and 60),
    constraint registrations_nim_check
        check (length(nim) <= 30),
    constraint registrations_email_check
        check (length(btrim(email)) between 3 and 254),
    constraint registrations_phone_check
        check (length(btrim(phone)) between 7 and 20)
);

-- 2. Index untuk query daftar pendaftar, pendaftaran user, dan kuota.
create index if not exists registrations_event_id_idx
    on public.registrations (event_id);
create index if not exists registrations_user_id_idx
    on public.registrations (user_id);
create index if not exists registrations_event_status_idx
    on public.registrations (event_id, status);

-- 3. updated_at otomatis diperbarui.
create or replace function public.set_registrations_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists registrations_set_updated_at on public.registrations;
create trigger registrations_set_updated_at
before update on public.registrations
for each row execute function public.set_registrations_updated_at();

-- 4. Validasi bisnis dan kuota.
-- Mengunci row event saat pendaftaran dibuat/diaktifkan kembali agar dua
-- request bersamaan tidak dapat melewati batas kuota.
create or replace function public.validate_registration_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid;
    v_event public.events%rowtype;
    v_active_count integer;
    v_is_participant boolean;
    v_is_organizer boolean;
begin
    v_uid := (select auth.uid());
    if v_uid is null then
        raise exception 'Silakan login terlebih dahulu.';
    end if;

    if tg_op = 'INSERT' then
        if new.user_id is distinct from v_uid then
            raise exception 'Pendaftaran hanya dapat dibuat untuk akun sendiri.';
        end if;

        select * into v_event
        from public.events
        where id = new.event_id
        for update;

        if not found then
            raise exception 'Event tidak ditemukan.';
        end if;
        if v_event.created_by = v_uid then
            raise exception 'Kamu tidak bisa mendaftar ke event milikmu sendiri.';
        end if;
        if v_event.event_date < current_date then
            raise exception 'Pendaftaran ditutup karena event sudah lewat.';
        end if;

        -- Sesuai FakeRegistrationRepository, pendaftaran baru langsung CONFIRMED.
        if new.status is distinct from 'CONFIRMED' then
            raise exception 'Pendaftaran baru harus berstatus CONFIRMED.';
        end if;

        select count(*)::integer into v_active_count
        from public.registrations r
        where r.event_id = new.event_id
          and r.status in ('PENDING', 'CONFIRMED');

        if v_active_count >= v_event.quota then
            raise exception 'Maaf, kuota event ini sudah penuh.';
        end if;

        return new;
    end if;

    -- Identitas peserta dan event tidak boleh dipindahkan.
    if new.user_id is distinct from old.user_id
       or new.event_id is distinct from old.event_id then
        raise exception 'Peserta dan event pada pendaftaran tidak boleh diubah.';
    end if;

    select * into v_event
    from public.events
    where id = old.event_id
    for update;

    if not found then
        raise exception 'Event tidak ditemukan.';
    end if;

    v_is_participant := old.user_id = v_uid;
    v_is_organizer := v_event.created_by = v_uid;

    if not v_is_participant and not v_is_organizer then
        raise exception 'Kamu tidak berhak mengubah pendaftaran ini.';
    end if;

    -- Peserta hanya dapat mengubah data kontak dan membatalkan pendaftarannya.
    if v_is_participant and not v_is_organizer then
        if new.status is distinct from old.status
            and new.status <> 'CANCELLED' then
            raise exception 'Peserta hanya dapat membatalkan pendaftarannya sendiri.';
        end if;
    end if;

    -- Organizer boleh mengatur status, tetapi tidak boleh mengubah data identitas
    -- peserta melalui perubahan status.
    if v_is_organizer and not v_is_participant then
        if new.full_name is distinct from old.full_name
           or new.nim is distinct from old.nim
           or new.email is distinct from old.email
           or new.phone is distinct from old.phone then
           raise exception 'Penyelenggara hanya dapat mengubah status pendaftaran.';
        end if;
    end if;

    if new.status not in ('PENDING', 'CONFIRMED', 'CANCELLED') then
        raise exception 'Status pendaftaran tidak valid.';
    end if;

    -- Aktivasi kembali dari CANCELLED memeriksa tanggal dan kuota.
    if old.status = 'CANCELLED' and new.status in ('PENDING', 'CONFIRMED') then
        if v_event.event_date < current_date then
            raise exception 'Event sudah lewat, pendaftaran tidak bisa diaktifkan lagi.';
        end if;

        select count(*)::integer into v_active_count
        from public.registrations r
        where r.event_id = old.event_id
          and r.id <> old.id
          and r.status in ('PENDING', 'CONFIRMED');

        if v_active_count >= v_event.quota then
            raise exception 'Maaf, kuota event ini sudah penuh.';
        end if;
    end if;

    return new;
end;
$$;

drop trigger if exists registrations_validate_write on public.registrations;
create trigger registrations_validate_write
before insert or update on public.registrations
for each row execute function public.validate_registration_write();

-- 5. Row Level Security
alter table public.registrations enable row level security;

drop policy if exists "registrations_select_participant_or_organizer" on public.registrations;
create policy "registrations_select_participant_or_organizer"
on public.registrations for select
to authenticated
using (
    user_id = (select auth.uid())
    or exists (
        select 1 from public.events e
        where e.id = registrations.event_id
          and e.created_by = (select auth.uid())
    )
);

drop policy if exists "registrations_insert_own" on public.registrations;
create policy "registrations_insert_own"
on public.registrations for insert
to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists "registrations_update_participant_or_organizer" on public.registrations;
create policy "registrations_update_participant_or_organizer"
on public.registrations for update
to authenticated
using (
    user_id = (select auth.uid())
    or exists (
        select 1 from public.events e
        where e.id = registrations.event_id
          and e.created_by = (select auth.uid())
    )
)
with check (
    user_id = (select auth.uid())
    or exists (
        select 1 from public.events e
        where e.id = registrations.event_id
          and e.created_by = (select auth.uid())
    )
);

drop policy if exists "registrations_delete_own" on public.registrations;
create policy "registrations_delete_own"
on public.registrations for delete
to authenticated
using (user_id = (select auth.uid()));

grant select, insert, update, delete
on table public.registrations to authenticated;
grant usage, select
on sequence public.registrations_id_seq to authenticated;

-- 6. Verifikasi hasil. Tabel kosong sebelum ada pendaftaran adalah normal.
select
    id,
    event_id,
    user_id,
    full_name,
    nim,
    email,
    phone,
    status,
    created_at,
    updated_at
from public.registrations
order by created_at desc;

