-- 1. Tabel categories
create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null default '',
    icon_key text not null default 'apps',
    created_at timestamptz not null default now(),

    constraint categories_name_not_blank
        check (length(btrim(name)) > 0)
);

-- 2. Nama kategori unik tanpa membedakan huruf besar/kecil.
-- Contoh: "Seminar" dan "seminar" dianggap duplikat.
create unique index if not exists categories_name_lower_uidx
    on public.categories (lower(btrim(name)));

-- 3. RLS
alter table public.categories enable row level security;

-- Semua pengguna yang sudah login dapat melihat kategori.
drop policy if exists "categories_select_authenticated"
    on public.categories;
create policy "categories_select_authenticated"
    on public.categories
    for select
    to authenticated
    using (true);

-- CRUD kategori dibatasi ke pengguna yang sudah login.
-- Jika nanti hanya admin/pengelola tertentu yang boleh mengelola kategori,
-- policy INSERT/UPDATE/DELETE perlu diperketat menggunakan role/claims.
drop policy if exists "categories_insert_authenticated"
    on public.categories;
create policy "categories_insert_authenticated"
    on public.categories
    for insert
    to authenticated
    with check (true);

drop policy if exists "categories_update_authenticated"
    on public.categories;
create policy "categories_update_authenticated"
    on public.categories
    for update
    to authenticated
    using (true)
    with check (true);

drop policy if exists "categories_delete_authenticated"
    on public.categories;
create policy "categories_delete_authenticated"
    on public.categories
    for delete
    to authenticated
    using (true);

-- Hak akses tabel untuk role aplikasi Supabase.
grant select, insert, update, delete
    on table public.categories to authenticated;
grant usage, select
    on sequence public.categories_id_seq to authenticated;

-- 4. Seed kategori awal sesuai FakeDataSource.kt.
-- Aman dijalankan ulang: tidak menambahkan nama yang sudah ada
-- (pencocokan nama tidak sensitif kapitalisasi).
insert into public.categories (name, description, icon_key)
select seed.name, seed.description, seed.icon_key
from (
    values
        ('Seminar', 'Wawasan dari pembicara ahli', 'mic'),
        ('Workshop', 'Belajar langsung lewat praktik', 'laptop'),
        ('Competition', 'Tunjukkan kemampuan terbaikmu', 'trophy'),
        ('Organization', 'Kegiatan organisasi mahasiswa', 'groups'),
        ('Technology', 'Inovasi dan tren teknologi', 'laptop')
) as seed(name, description, icon_key)
where not exists (
    select 1
    from public.categories existing
    where lower(btrim(existing.name)) = lower(btrim(seed.name))
);

-- 5. Verifikasi hasil
select id, name, description, icon_key, created_at
from public.categories
order by id;