-- 1. Tabel favorites
create table if not exists public.favorites (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid(),
    event_id bigint not null,
    created_at timestamptz not null default now(),

    constraint favorites_user_fk
        foreign key (user_id) references public.profiles(id) on delete cascade,
    constraint favorites_event_fk
        foreign key (event_id) references public.events(id) on delete cascade,
    constraint favorites_user_event_unique unique (user_id, event_id)
);

-- 2. Index untuk mengambil favorit user dan mencari user yang menyimpan event.
-- Unique constraint di atas sudah menyediakan index gabungan (user_id, event_id).
create index if not exists favorites_event_id_idx
    on public.favorites (event_id);

-- 3. Row Level Security
alter table public.favorites enable row level security;

drop policy if exists "favorites_select_own" on public.favorites;
create policy "favorites_select_own"
on public.favorites for select
to authenticated
using (user_id = (select auth.uid()));

drop policy if exists "favorites_insert_own" on public.favorites;
create policy "favorites_insert_own"
on public.favorites for insert
to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists "favorites_delete_own" on public.favorites;
create policy "favorites_delete_own"
on public.favorites for delete
to authenticated
using (user_id = (select auth.uid()));

-- Tidak ada policy UPDATE karena toggle favorit cukup INSERT atau DELETE.
grant select, insert, delete
on table public.favorites to authenticated;
grant usage, select
on sequence public.favorites_id_seq to authenticated;

-- 4. Verifikasi. Hasil kosong adalah normal jika belum ada user menyimpan event.
select id, user_id, event_id, created_at
from public.favorites
order by created_at desc;