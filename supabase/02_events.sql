create table if not exists public.events (
    id bigint generated by default as identity primary key,
    title text not null,
    category_id bigint not null,
    created_by uuid not null default auth.uid(),
    event_date date not null,
    start_time time without time zone not null,
    end_time time without time zone not null,
    location text not null,
    quota integer not null,
    description text not null default '',
    image_url text,
    is_featured boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint events_title_length check (length(btrim(title)) between 5 and 80),
    constraint events_description_length check (length(btrim(description)) between 20 and 1000),
    constraint events_location_length check (length(btrim(location)) between 3 and 100),
    constraint events_quota_range check (quota between 1 and 10000),
    constraint events_time_order check (end_time > start_time),
    constraint events_category_fk
        foreign key (category_id) references public.categories(id) on delete restrict,
    constraint events_created_by_fk
        foreign key (created_by) references public.profiles(id) on delete restrict
);

create index if not exists events_category_id_idx
    on public.events(category_id);
create index if not exists events_created_by_idx
    on public.events(created_by);
create index if not exists events_event_date_idx
    on public.events(event_date);
create index if not exists events_featured_date_idx
    on public.events(is_featured, event_date desc);

-- Keep updated_at current on every update.
create or replace function public.set_events_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists events_set_updated_at on public.events;
create trigger events_set_updated_at
before update on public.events
for each row execute function public.set_events_updated_at();

alter table public.events enable row level security;

drop policy if exists "events_select_authenticated" on public.events;
create policy "events_select_authenticated"
on public.events for select
to authenticated
using (true);

drop policy if exists "events_insert_own" on public.events;
create policy "events_insert_own"
on public.events for insert
to authenticated
with check (created_by = (select auth.uid()));

drop policy if exists "events_update_own" on public.events;
create policy "events_update_own"
on public.events for update
to authenticated
using (created_by = (select auth.uid()))
with check (created_by = (select auth.uid()));

drop policy if exists "events_delete_own" on public.events;
create policy "events_delete_own"
on public.events for delete
to authenticated
using (created_by = (select auth.uid()));

grant select, insert, update, delete on table public.events to authenticated;
grant usage, select on sequence public.events_id_seq to authenticated;

-- Quick verification: an empty result is expected before events are created.
select
    id,
    title,
    category_id,
    created_by,
    event_date,
    start_time,
    end_time,
    location,
    quota,
    description,
    image_url,
    is_featured,
    created_at,
    updated_at
from public.events
order by event_date, start_time;
