-- ---------------------------------------------------------------------
-- 0. Helper updated_at (aman jika sudah dibuat oleh auth_profile_setup.sql)
-- ---------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------
-- 1. CATEGORIES - Fitur Fadhil
-- Nama kategori unik tanpa membedakan huruf besar/kecil.
-- Semua user login dapat membaca kategori; pemilik mengelola kategorinya.
-- ---------------------------------------------------------------------
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  description text not null default '',
  icon_key    text not null default 'apps',
  created_by  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint categories_name_not_blank check (length(trim(name)) > 0)
);

create unique index if not exists categories_name_unique_ci
  on public.categories (lower(trim(name)));

 drop trigger if exists categories_touch_updated_at on public.categories;
create trigger categories_touch_updated_at
  before update on public.categories
  for each row execute function public.touch_updated_at();

alter table public.categories enable row level security;

drop policy if exists "categories_select_authenticated" on public.categories;
create policy "categories_select_authenticated"
  on public.categories for select to authenticated
  using (true);

drop policy if exists "categories_insert_own" on public.categories;
create policy "categories_insert_own"
  on public.categories for insert to authenticated
  with check (created_by = (select auth.uid()));

drop policy if exists "categories_update_own" on public.categories;
create policy "categories_update_own"
  on public.categories for update to authenticated
  using (created_by = (select auth.uid()))
  with check (created_by = (select auth.uid()));

drop policy if exists "categories_delete_own" on public.categories;
create policy "categories_delete_own"
  on public.categories for delete to authenticated
  using (created_by = (select auth.uid()));

-- ---------------------------------------------------------------------
-- 2. EVENTS - Fitur My Events / Event Organizer (Zaqy)
-- Organizer adalah nama profil yang diambil melalui join profiles.
-- ---------------------------------------------------------------------
create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  title       text not null,
  category_id bigint not null references public.categories(id) on delete restrict,
  created_by  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  event_date  date not null,
  start_time  time not null,
  end_time    time not null,
  location    text not null,
  quota       integer not null check (quota > 0),
  description text not null default '',
  image_url   text,
  is_featured boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint events_title_not_blank check (length(trim(title)) > 0),
  constraint events_location_not_blank check (length(trim(location)) > 0),
  constraint events_time_order check (end_time > start_time)