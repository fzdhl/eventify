-- 4. REGISTRATIONS - Fitur Raihan
-- Peserta hanya mengelola pendaftarannya sendiri.
-- Organizer dapat membaca peserta event miliknya dan mengubah statusnya.
-- ---------------------------------------------------------------------
create table if not exists public.registrations (
  id         bigint generated by default as identity primary key,
  event_id   bigint not null references public.events(id) on delete cascade,
  user_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,
  full_name  text not null,
  nim        text not null,
  email      text not null,
  phone      text not null default '',
  status     text not null default 'CONFIRMED'
             check (status in ('PENDING', 'CONFIRMED', 'CANCELLED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint registrations_one_per_user_event unique (event_id, user_id),
  constraint registrations_name_not_blank check (length(trim(full_name)) > 0),
  constraint registrations_nim_not_blank check (length(trim(nim)) > 0)
);

create index if not exists registrations_user_id_idx on public.registrations(user_id);
create index if not exists registrations_event_id_idx on public.registrations(event_id);
create index if not exists registrations_status_idx on public.registrations(status);

