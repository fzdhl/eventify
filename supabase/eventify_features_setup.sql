-- ---------------------------------------------------------------------
-- 0. Helper updated_at (aman jika sudah dibuat oleh auth_profile_setup.sql)
-- ---------------------------------------------------------------------
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

