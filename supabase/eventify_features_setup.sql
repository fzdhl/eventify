-- Validasi kapasitas, tanggal, dan larangan organizer mendaftar ke event sendiri.
create or replace function public.validate_registration_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.events%rowtype;
  v_active_count integer;
  v_uid uuid;
begin
  v_uid := (select auth.uid());

  select * into v_event
  from public.events
  where id = new.event_id;

  if not found then
    raise exception 'Event tidak ditemukan.';
  end if;

  if tg_op = 'INSERT' then
    if v_uid is null or new.user_id <> v_uid then
      raise exception 'Pendaftaran hanya boleh dibuat untuk akun sendiri.';
    end if;
    if v_event.created_by = v_uid then
      raise exception 'Penyelenggara tidak dapat mendaftar ke event miliknya sendiri.';
    end if;
    if v_event.event_date < current_date then
      raise exception 'Pendaftaran ditutup karena event sudah lewat.';
    end if;
  else
    if new.event_id <> old.event_id or new.user_id <> old.user_id then
      raise exception 'Event dan pemilik pendaftaran tidak boleh diubah.';
    end if;
    -- Peserta boleh membatalkan pendaftaran sendiri, tetapi tidak boleh
    -- mengonfirmasi dirinya sendiri atau mengubah status ke PENDING.
    if v_uid = old.user_id and v_uid <> v_event.created_by then
      if new.status <> old.status and new.status <> 'CANCELLED' then
        raise exception 'Peserta hanya boleh membatalkan pendaftarannya sendiri.';
      end if;
    elsif v_uid <> v_event.created_by then
      raise exception 'Hanya peserta atau penyelenggara event yang boleh mengubah pendaftaran.';
    end if;
  end if;

  if new.status <> 'CANCELLED' then
    select count(*) into v_active_count
    from public.registrations r
    where r.event_id = new.event_id
      and r.status <> 'CANCELLED'
      and (tg_op = 'INSERT' or r.id <> new.id);

    if v_active_count >= v_event.quota then
      raise exception 'Kuota event sudah penuh.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists registrations_validate_write on public.registrations;
create trigger registrations_validate_write
  before insert or update on public.registrations
  for each row execute function public.validate_registration_write();

