-- 1. CATEGORIES - Fitur Fadhil
-- Nama kategori unik tanpa membedakan huruf besar/kecil.
-- Semua user login dapat membaca kategori; pemilik mengelola kategorinya.
-- ---------------------------------------------------------------------
create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text not null,
  description text not null default '',
  icon_key    text not null default 'apps',
  created_by  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint categories_name_not_blank check (length(trim(name)) > 0)
);

create unique index if not exists categories_name_unique_ci
  on public.categories (lower(trim(name)));

 drop trigger if exists categories_touch_updated_at on public.categories;
create trigger categories_touch_updated_at
  before update on public.categories
  for each row execute function public.touch_updated_at();

