-- 1. Tabel reviews
create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    event_id bigint not null,
    user_id uuid not null default auth.uid(),
    rating integer not null,
    comment text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz,

    constraint reviews_event_fk
        foreign key (event_id) references public.events(id) on delete cascade,
    constraint reviews_user_fk
        foreign key (user_id) references public.profiles(id) on delete cascade,
    constraint reviews_event_user_unique unique (event_id, user_id),
    constraint reviews_rating_check check (rating between 1 and 5),
    constraint reviews_comment_length_check
        check (length(btrim(comment)) between 10 and 500)
);

-- 2. Index
create index if not exists reviews_event_id_idx
    on public.reviews (event_id);
create index if not exists reviews_user_id_idx
    on public.reviews (user_id);

-- 3. Validasi aturan bisnis.
-- SECURITY DEFINER diperlukan agar pemeriksaan relasi pendaftaran dapat
-- dilakukan secara konsisten meskipun RLS registrations membatasi baris.
create or replace function public.validate_review_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_uid uuid;
    v_event public.events%rowtype;
begin
    v_uid := (select auth.uid());
    if v_uid is null then
        raise exception 'Silakan login terlebih dahulu.';
    end if;

    if new.rating not between 1 and 5 then
        raise exception 'Rating harus 1 sampai 5 bintang.';
    end if;
    if length(btrim(new.comment)) not between 10 and 500 then
        raise exception 'Ulasan minimal 10 dan maksimal 500 karakter.';
    end if;

    if tg_op = 'INSERT' then
        if new.user_id is distinct from v_uid then
            raise exception 'Ulasan hanya boleh dibuat untuk akun sendiri.';
        end if;

        select * into v_event
        from public.events
        where id = new.event_id;

        if not found then
            raise exception 'Event tidak ditemukan.';
        end if;
        if v_event.created_by = v_uid then
            raise exception 'Penyelenggara tidak bisa mengulas event sendiri.';
        end if;
        if v_event.event_date >= current_date then
            raise exception 'Ulasan bisa ditulis setelah event selesai.';
        end if;
        if not exists (
            select 1
            from public.registrations r
            where r.event_id = new.event_id
              and r.user_id = v_uid
              and r.status = 'CONFIRMED'
        ) then
            raise exception 'Hanya peserta yang hadir (Confirmed) yang bisa memberi ulasan.';
        end if;
    else
        if new.user_id is distinct from old.user_id
           or new.event_id is distinct from old.event_id then
            raise exception 'Pemilik dan event ulasan tidak boleh diubah.';
        end if;
        if old.user_id is distinct from v_uid then
            raise exception 'Kamu hanya bisa mengubah ulasanmu sendiri.';
        end if;

        new.updated_at := now();
    end if;

    return new;
end;
$$;

drop trigger if exists reviews_validate_write on public.reviews;
create trigger reviews_validate_write
before insert or update on public.reviews
for each row execute function public.validate_review_write();

-- 4. Row Level Security
alter table public.reviews enable row level security;

drop policy if exists "reviews_select_authenticated" on public.reviews;
create policy "reviews_select_authenticated"
on public.reviews for select
to authenticated
using (true);

drop policy if exists "reviews_insert_own" on public.reviews;
create policy "reviews_insert_own"
on public.reviews for insert
to authenticated
with check (user_id = (select auth.uid()));

drop policy if exists "reviews_update_own" on public.reviews;
create policy "reviews_update_own"
on public.reviews for update
to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists "reviews_delete_own" on public.reviews;
create policy "reviews_delete_own"
on public.reviews for delete
to authenticated
using (user_id = (select auth.uid()));

grant select, insert, update, delete
on table public.reviews to authenticated;
grant usage, select
on sequence public.reviews_id_seq to authenticated;

-- 5. Verifikasi. Hasil kosong normal sebelum ada ulasan.
select
    id,
    event_id,
    user_id,
    rating,
    comment,
    created_at,
    updated_at
from public.reviews;